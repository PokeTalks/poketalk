function renderPuzzle() {
  let size = 3;
  let tiles = [];
  let moves = 0;
  let completed = false;
  const picture = "poketalk/pikachu.png";

  function shuffle() {
    tiles = [...Array(size * size - 1).keys()].map(n => n + 1);
    tiles.push(0);
    moves = 0;
    completed = false;

    // Legal moves se shuffle, taaki puzzle solvable rahe
    let previousBlank = -1;

    for (let i = 0; i < 200; i++) {
      const blank = tiles.indexOf(0);
      const neighbors = [
        blank - size,
        blank + size,
        blank % size ? blank - 1 : -1,
        blank % size < size - 1 ? blank + 1 : -1
      ].filter(n =>
        n >= 0 &&
        n < tiles.length &&
        Math.abs(Math.floor(n / size) - Math.floor(blank / size)) +
        Math.abs(n % size - blank % size) === 1 &&
        n !== previousBlank
      );

      const chosen = neighbors[Math.floor(Math.random() * neighbors.length)];
      previousBlank = blank;
      [tiles[blank], tiles[chosen]] = [tiles[chosen], tiles[blank]];
    }

    // Solved starting board ko avoid karo
    if (isSolved()) {
      [tiles[0], tiles[1]] = [tiles[1], tiles[0]];
    }

    draw();
  }

  function isSolved() {
    return tiles.every((v, i) => v === (i + 1) % (size * size));
  }

  function draw() {
    completed = isSolved();

    shell(`
      <div class="puzzle-heading">
        <h3>🧩 Pokémon Picture Puzzle</h3>
        <p>Tiles ko sahi order mein jodo aur picture complete karo!</p>
      </div>

      <div style="display:flex;justify-content:center;gap:18px;flex-wrap:wrap;margin:12px 0">
        <span>🖐️ Moves: <b>${moves}</b></span>
        <span>📐 Grid: <b>${size} × ${size}</b></span>
      </div>

      ${completed ? `
        <div style="text-align:center;margin:16px 0">
          <h3>🎉 Picture Complete!</h3>
          <p>Great job, Trainer! Tumne ${moves} moves mein puzzle solve kiya.</p>
          <img src="${picture}" alt="Completed Pokémon picture"
            style="width:min(280px,80%);border-radius:16px;box-shadow:0 8px 28px #0005">
        </div>
      ` : `
        <div class="puzzle-grid"
          style="grid-template-columns:repeat(${size},min(26vw,90px));gap:4px;margin:18px auto;justify-content:center">
          ${tiles.map((v, i) => `
            <button
              class="puzzle-tile ${v === 0 ? "empty" : ""}"
              data-tile="${i}"
              aria-label="${v === 0 ? "Empty space" : "Move tile " + v}"
              ${v === 0 ? "disabled" : ""}
              style="
                width:min(26vw,90px);
                height:min(26vw,90px);
                box-sizing:border-box;
                border-radius:8px;
                ${v ? `
                  background-image:url('${picture}');
                  background-size:${size * 100}% ${size * 100}%;
                  background-position:
                    ${((v - 1) % size) / (size - 1) * 100}%
                    ${Math.floor((v - 1) / size) / (size - 1) * 100}%;
                  border:2px solid #ffffff70;
                  cursor:pointer;
                ` : `
                  background:rgba(255,255,255,.08);
                  border:2px dashed #ffffff50;
                `}
                color:transparent;
              ">
              
              ${v ? `<span style="display:flex;align-items:center;justify-content:center;width:28px;height:28px;margin:auto;border-radius:50%;background:rgba(10,10,30,.9);color:#ffffff;font-size:16px;font-weight:900;border:2px solid #00f5ff;box-shadow:0 0 10px #00f5ff;text-shadow:0 0 5px #00f5ff;">${v}</span>` : ""}

            </button>
          `).join("")}
        </div>

        <p class="game-status" style="text-align:center">
          Tap an adjacent tile to slide it into the empty space.
        </p>
      `}

      <div class="puzzle-controls" style="justify-content:center;gap:10px;flex-wrap:wrap">
        <label>
          Difficulty
          <select id="puzzleSize">
            <option value="3" ${size === 3 ? "selected" : ""}>Easy · 3 × 3</option>
            <option value="4" ${size === 4 ? "selected" : ""}>Hard · 4 × 4</option>
          </select>
        </label>
        <button id="puzzleShuffle">${completed ? "Play again ↻" : "Restart ↻"}</button>
      </div>

      <details style="text-align:center;margin-top:12px">
        <summary style="cursor:pointer">👀 Picture preview</summary>
        <img src="${picture}" alt="Pokémon puzzle preview"
          style="width:150px;max-width:70%;margin-top:12px;border-radius:12px">
      </details>
    `);

    modalBody.querySelectorAll("[data-tile]").forEach(button => {
      button.onclick = () => {
        const i = Number(button.dataset.tile);
        const blank = tiles.indexOf(0);

        const adjacent =
          Math.abs(Math.floor(i / size) - Math.floor(blank / size)) +
          Math.abs(i % size - blank % size) === 1;

        if (!adjacent || completed) return;

        [tiles[i], tiles[blank]] = [tiles[blank], tiles[i]];
        moves++;
        draw();
      };
    });

    $("#puzzleSize").onchange = e => {
      size = Number(e.target.value);
      shuffle();
    };

    $("#puzzleShuffle").onclick = shuffle;
  }

  shuffle();
}
